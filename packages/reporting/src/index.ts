import PDFDocument from 'pdfkit';
import { StorageClient } from '@circuitsoul/storage';

export interface ReportOptions {
  title: string;
  content: string;
  author?: string;
  createdAt?: Date;
}

export async function generatePdfReport(options: ReportOptions): Promise<Buffer> {
  const document = new PDFDocument({ size: 'A4', margin: 48 });
  const chunks: Buffer[] = [];

  document.on('data', chunk => chunks.push(chunk));
  document.on('end', () => undefined);

  document.fontSize(22).fillColor('#020817').text(options.title, { underline: true });
  document.moveDown(0.5);
  document.fontSize(10).fillColor('#64748b').text(`Audited by: ${options.author ?? 'CircuitSoul Shield'}`);
  document.fontSize(9).fillColor('#64748b').text(`Timestamp: ${options.createdAt?.toISOString() ?? new Date().toISOString()}`);
  document.moveDown(1.5);
  document.fontSize(11).fillColor('#1e293b').text(options.content, { lineGap: 5 });
  document.end();

  return new Promise((resolve, reject) => {
    document.on('end', () => resolve(Buffer.concat(chunks)));
    document.on('error', reject);
  });
}

export async function buildStatutoryNDPRCertificatePdf(data: {
  certificateId: string;
  organizationName: string;
  timestamp: string;
  overallScore: number;
  compliant: boolean;
  tier: string;
  pillars: Array<{
    pillar: string;
    score: number;
    maxScore: number;
    regulatoryReference: string;
    findings: string;
  }>;
  requiredRemediations: string[];
}): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margin: 48 });
  const chunks: Buffer[] = [];

  doc.on('data', chunk => chunks.push(chunk));
  doc.on('end', () => undefined);

  // Header Bar
  doc.fontSize(18).fillColor('#0284c7').text('CIRCUITSOUL SHIELD', { characterSpacing: 1.5 });
  doc.fontSize(10).fillColor('#475569').text('Digital Infrastructure & Data Sovereignty Certification');
  doc.moveDown(0.8);
  doc.moveTo(48, doc.y).lineTo(547, doc.y).strokeColor('#e2e8f0').stroke();
  doc.moveDown(1.2);

  // Certificate Box
  doc.fontSize(12).fillColor('#64748b').text('OFFICIAL STATUTORY COMPLIANCE AUDIT CERTIFICATE');
  doc.fontSize(20).fillColor('#0f172a').text(data.organizationName);
  doc.moveDown(0.4);
  doc.fontSize(10).fillColor('#64748b').text(`Certificate Reference: ${data.certificateId}   |   Issued: ${new Date(data.timestamp).toUTCString()}`);
  doc.moveDown(1);

  // Overall Score & Status
  const statusColor = data.overallScore >= 80 ? '#10b981' : data.overallScore >= 60 ? '#f59e0b' : '#ef4444';
  doc.rect(48, doc.y, 499, 48).fillAndStroke('#f8fafc', '#e2e8f0');
  const badgeY = doc.y - 36;
  doc.fontSize(14).fillColor('#0f172a').text(`Statutory Score: ${data.overallScore}/100`, 64, badgeY);
  doc.fontSize(11).fillColor(statusColor).text(`Status: ${data.tier.replace('_', ' ')} (${data.compliant ? 'PASSED' : 'ACTION REQUIRED'})`, 310, badgeY);
  doc.moveDown(2);

  // Pillar Breakdown
  doc.fontSize(13).fillColor('#0f172a').text('Statutory Assessment Pillars (NDPA 2023 / NDPR 2019)');
  doc.moveDown(0.5);

  data.pillars.forEach((p, idx) => {
    doc.fontSize(11).fillColor('#1e293b').text(`${idx + 1}. ${p.pillar} — [${p.score}/${p.maxScore} pts]`);
    doc.fontSize(9).fillColor('#64748b').text(`   Regulatory Standard: ${p.regulatoryReference}`);
    doc.fontSize(9).fillColor('#334155').text(`   Findings: ${p.findings}`, { lineGap: 2 });
    doc.moveDown(0.6);
  });

  // Remediations Section
  if (data.requiredRemediations.length > 0) {
    doc.moveDown(0.5);
    doc.fontSize(12).fillColor('#b91c1c').text('Mandatory Remediation Action Plan');
    doc.moveDown(0.3);
    data.requiredRemediations.forEach((r, idx) => {
      doc.fontSize(9).fillColor('#7f1d1d').text(`• [P${idx + 1}] ${r}`, { lineGap: 2 });
    });
  }

  // Legal Disclaimer Footer
  doc.moveDown(1.5);
  doc.moveTo(48, doc.y).lineTo(547, doc.y).strokeColor('#e2e8f0').stroke();
  doc.moveDown(0.8);
  doc.fontSize(8).fillColor('#94a3b8').text(
    'LEGAL NOTICE: This assessment certificate is generated by CircuitSoul Shield based on verified infrastructure scan telemetry and authorized client disclosures. In accordance with the Nigeria Data Protection Commission (NDPC) guidelines, annual filing must be conducted by an accredited DPCO.',
    { lineGap: 2 }
  );

  doc.end();

  return new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });
}

export async function storeReport(
  storageClient: StorageClient,
  key: string,
  reportBuffer: Buffer,
  contentType = 'application/pdf'
): Promise<string> {
  return storageClient.uploadObject(key, reportBuffer, contentType);
}

export async function buildNdprReport(content: string): Promise<Buffer> {
  return generatePdfReport({
    title: 'CircuitSoul NDPR Report',
    content,
    author: 'CircuitSoul Shield',
    createdAt: new Date()
  });
}

export async function buildExecutiveSummary(summary: string): Promise<Buffer> {
  return generatePdfReport({
    title: 'Executive Summary',
    content: summary,
    author: 'CircuitSoul Reporting',
    createdAt: new Date()
  });
}
